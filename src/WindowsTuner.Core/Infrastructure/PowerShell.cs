using System.Text;

namespace WindowsTuner.Core.Infrastructure;

/// <summary>
/// Runs Windows PowerShell 5.1 (always present on Windows 10/11). Each script is written as a plain .ps1 file
/// to the protected scripts folder and run with -File — no encoded commands and no execution-policy bypass,
/// which is what malware does and what antivirus heuristics rightly look for.
/// </summary>
public static class PowerShell
{
    public static string Executable =>
        Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.System),
            "WindowsPowerShell", "v1.0", "powershell.exe");

    public static string Wrap(string script) =>
        "# Generated by WindowsTuner — safe to delete.\r\n" +
        "$ProgressPreference = 'SilentlyContinue'\r\n" +
        "[Console]::OutputEncoding = [System.Text.Encoding]::UTF8\r\n" +
        script + "\r\n";

    public static async Task<ProcessResult> RunAsync(string script, Action<string>? onLine = null, CancellationToken ct = default)
    {
        var path = SecureScripts.NewPath(".ps1");
        // UTF-8 with BOM so Windows PowerShell 5.1 reads non-ASCII text correctly.
        await File.WriteAllTextAsync(path, Wrap(script), new UTF8Encoding(encoderShouldEmitUTF8Identifier: true), ct);
        try
        {
            var exe = File.Exists(Executable) ? Executable : "powershell.exe";
            // RemoteSigned lets our own local script run on PCs where the default policy is "Restricted",
            // while still refusing unsigned scripts downloaded from the internet.
            return await ProcessRunner.RunAsync(exe,
                $"-NoProfile -NonInteractive -ExecutionPolicy RemoteSigned -File \"{path}\"",
                onLine, Encoding.UTF8, ct);
        }
        finally
        {
            SecureScripts.TryDelete(path);
        }
    }

    /// <summary>Escapes a value for use inside a single-quoted PowerShell string.</summary>
    public static string Quote(string value) => "'" + value.Replace("'", "''") + "'";
}
